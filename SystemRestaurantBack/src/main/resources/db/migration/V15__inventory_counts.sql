-- Essential Plus: immutable physical count, with one adjustment per discrepancy.
-- Existing stock and ledger entries are preserved.
CREATE TABLE inventory_counts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL UNIQUE,
    reason VARCHAR(250) NOT NULL,
    recorded_by_user_id BIGINT NOT NULL REFERENCES app_users (id),
    recorded_by_username VARCHAR(80) NOT NULL,
    counted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_count_reason CHECK (LENGTH(TRIM(reason)) >= 5)
);

CREATE TABLE inventory_count_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    count_id BIGINT NOT NULL REFERENCES inventory_counts (id),
    ingredient_id BIGINT NOT NULL REFERENCES inventory_ingredients (id),
    ingredient_name VARCHAR(120) NOT NULL,
    unit VARCHAR(10) NOT NULL,
    expected_version BIGINT NOT NULL,
    expected_quantity NUMERIC(14, 3) NOT NULL,
    counted_quantity NUMERIC(14, 3) NOT NULL,
    unit_cost_snapshot NUMERIC(14, 4),
    movement_id BIGINT UNIQUE REFERENCES inventory_movements (id),
    CONSTRAINT uk_inventory_count_ingredient UNIQUE (count_id, ingredient_id),
    CONSTRAINT ck_inventory_count_quantities CHECK (expected_quantity >= 0 AND counted_quantity >= 0),
    CONSTRAINT ck_inventory_count_cost CHECK (unit_cost_snapshot IS NULL OR unit_cost_snapshot >= 0)
);

CREATE INDEX idx_inventory_counts_time ON inventory_counts (counted_at DESC, id DESC);
