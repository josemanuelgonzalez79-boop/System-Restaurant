-- Essential Pro: reservations belong to the one restaurant in this installation.
-- PostgreSQL enforces non-overlapping time slots even across simultaneous tablets.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES branches (id),
    service_point_id BIGINT NOT NULL REFERENCES service_points (id),
    guest_name VARCHAR(120) NOT NULL,
    guest_phone VARCHAR(30),
    guest_count INTEGER NOT NULL,
    notes VARCHAR(500),
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'BOOKED',
    order_id BIGINT UNIQUE REFERENCES restaurant_orders (id),
    created_by_user_id BIGINT NOT NULL REFERENCES app_users (id),
    created_by_username VARCHAR(80) NOT NULL,
    updated_by_username VARCHAR(80) NOT NULL,
    cancel_reason VARCHAR(250),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reservations_guest_name CHECK (LENGTH(TRIM(guest_name)) > 0),
    CONSTRAINT ck_reservations_guest_count CHECK (guest_count BETWEEN 1 AND 99),
    CONSTRAINT ck_reservations_period CHECK (end_at > start_at),
    CONSTRAINT ck_reservations_status CHECK (status IN ('BOOKED', 'SEATED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT ck_reservations_order CHECK (
        (status = 'SEATED' AND order_id IS NOT NULL)
        OR (status <> 'SEATED' AND order_id IS NULL)
    )
);

ALTER TABLE reservations ADD CONSTRAINT ex_reservations_table_time
    EXCLUDE USING gist (
        service_point_id WITH =,
        tstzrange(start_at, end_at, '[)') WITH &&
    ) WHERE (status IN ('BOOKED', 'SEATED'));

CREATE INDEX idx_reservations_date ON reservations (start_at, id);
CREATE INDEX idx_reservations_table_future ON reservations (service_point_id, end_at)
    WHERE status = 'BOOKED';

CREATE TABLE reservation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations (id),
    action VARCHAR(20) NOT NULL,
    detail VARCHAR(250) NOT NULL,
    actor_user_id BIGINT NOT NULL REFERENCES app_users (id),
    actor_username VARCHAR(80) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reservation_event_action CHECK (
        action IN ('CREATED', 'RESCHEDULED', 'CANCELLED', 'NO_SHOW', 'SEATED')
    )
);

CREATE INDEX idx_reservation_events_history ON reservation_events (reservation_id, occurred_at, id);
