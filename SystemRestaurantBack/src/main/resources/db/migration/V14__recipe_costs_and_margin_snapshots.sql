-- Plus block 4: reference ingredient costs and immutable cost at dispatch.
-- Old movements remain unvalued: a later cost cannot rewrite their history.
ALTER TABLE inventory_ingredients
    ADD COLUMN unit_cost NUMERIC(14, 4),
    ADD CONSTRAINT ck_inventory_unit_cost CHECK (unit_cost IS NULL OR unit_cost >= 0);

CREATE TABLE inventory_cost_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL REFERENCES inventory_ingredients (id),
    previous_unit_cost NUMERIC(14, 4),
    new_unit_cost NUMERIC(14, 4) NOT NULL,
    reason VARCHAR(250) NOT NULL,
    changed_by_user_id BIGINT NOT NULL REFERENCES app_users (id),
    changed_by_username VARCHAR(80) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_cost_change_value CHECK (new_unit_cost >= 0),
    CONSTRAINT ck_inventory_cost_change_reason CHECK (LENGTH(TRIM(reason)) >= 5)
);
CREATE INDEX idx_inventory_cost_changes_ingredient_time
    ON inventory_cost_changes (ingredient_id, changed_at DESC, id DESC);

ALTER TABLE inventory_movements
    ADD COLUMN unit_cost_snapshot NUMERIC(14, 4),
    ADD COLUMN cost_amount_snapshot NUMERIC(28, 7),
    ADD CONSTRAINT ck_inventory_movement_cost_pair CHECK (
        (unit_cost_snapshot IS NULL AND cost_amount_snapshot IS NULL)
        OR (unit_cost_snapshot >= 0 AND cost_amount_snapshot IS NOT NULL
            AND movement_type IN ('ORDER_CONSUMPTION', 'ORDER_REVERSAL')
            AND cost_amount_snapshot = quantity_delta * unit_cost_snapshot)
    );
