-- Essential Plus: each installation has one local restaurant and its own stock ledger.
CREATE TABLE inventory_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    unit VARCHAR(10) NOT NULL,
    stock_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0,
    minimum_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_unit CHECK (unit IN ('PIECE', 'KG', 'L')),
    CONSTRAINT ck_inventory_stock CHECK (stock_quantity >= 0),
    CONSTRAINT ck_inventory_minimum CHECK (minimum_quantity >= 0)
);

CREATE UNIQUE INDEX uk_inventory_ingredients_name_ci ON inventory_ingredients (LOWER(name));

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL UNIQUE,
    ingredient_id BIGINT NOT NULL REFERENCES inventory_ingredients (id),
    movement_type VARCHAR(20) NOT NULL,
    quantity_delta NUMERIC(14, 3) NOT NULL,
    stock_after NUMERIC(14, 3) NOT NULL,
    reason VARCHAR(250) NOT NULL,
    recorded_by_user_id BIGINT NOT NULL REFERENCES app_users (id),
    recorded_by_username VARCHAR(80) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_movement_type CHECK (movement_type IN ('PURCHASE', 'USE', 'WASTE', 'ADJUSTMENT')),
    CONSTRAINT ck_inventory_movement_delta CHECK (quantity_delta <> 0),
    CONSTRAINT ck_inventory_movement_stock CHECK (stock_after >= 0),
    CONSTRAINT ck_inventory_movement_reason CHECK (LENGTH(TRIM(reason)) > 0)
);

CREATE INDEX idx_inventory_movements_ingredient_time
    ON inventory_movements (ingredient_id, occurred_at DESC, id DESC);
