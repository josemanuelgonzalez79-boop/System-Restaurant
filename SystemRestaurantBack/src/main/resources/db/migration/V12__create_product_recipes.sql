-- Essential Plus: a recipe describes the ingredients for one product or one modifier option.
-- Stock will be consumed by a separate migration and service in a later block.
CREATE TABLE inventory_recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES products (id),
    modifier_option_id BIGINT REFERENCES product_modifier_options (id),
    version BIGINT NOT NULL DEFAULT 0,
    updated_by_user_id BIGINT NOT NULL REFERENCES app_users (id),
    updated_by_username VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_recipe_owner CHECK (
        (product_id IS NOT NULL AND modifier_option_id IS NULL)
        OR (product_id IS NULL AND modifier_option_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uk_inventory_recipe_product ON inventory_recipes (product_id)
    WHERE product_id IS NOT NULL;
CREATE UNIQUE INDEX uk_inventory_recipe_option ON inventory_recipes (modifier_option_id)
    WHERE modifier_option_id IS NOT NULL;

CREATE TABLE inventory_recipe_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES inventory_recipes (id),
    ingredient_id BIGINT NOT NULL REFERENCES inventory_ingredients (id),
    quantity NUMERIC(14, 3) NOT NULL,
    CONSTRAINT ck_inventory_recipe_quantity CHECK (quantity > 0),
    CONSTRAINT uk_inventory_recipe_ingredient UNIQUE (recipe_id, ingredient_id)
);

CREATE INDEX idx_inventory_recipe_lines_ingredient ON inventory_recipe_lines (ingredient_id);
