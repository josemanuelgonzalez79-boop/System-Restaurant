CREATE TABLE restaurant_settings (
    id BIGINT PRIMARY KEY,
    business_name VARCHAR(120) NOT NULL,
    display_name VARCHAR(80) NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    timezone VARCHAR(60) NOT NULL,
    primary_color VARCHAR(7) NOT NULL,
    secondary_color VARCHAR(7) NOT NULL,
    phone VARCHAR(30),
    address VARCHAR(250),
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_restaurant_settings_singleton CHECK (id = 1),
    CONSTRAINT ck_restaurant_settings_currency CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_restaurant_settings_primary_color CHECK (primary_color ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_restaurant_settings_secondary_color CHECK (secondary_color ~ '^#[0-9A-Fa-f]{6}$')
);

