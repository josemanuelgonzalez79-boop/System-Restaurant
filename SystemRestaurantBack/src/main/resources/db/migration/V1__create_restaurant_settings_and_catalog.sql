CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(250),
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_categories_sort_order CHECK (sort_order >= 0)
);

CREATE UNIQUE INDEX uk_categories_name_ci ON categories (LOWER(name));
CREATE INDEX idx_categories_active_sort ON categories (active, sort_order, name);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories (id),
    sku VARCHAR(40),
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    price NUMERIC(12, 2) NOT NULL,
    destination VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_destination CHECK (destination IN ('KITCHEN', 'BAR', 'NONE'))
);

CREATE UNIQUE INDEX uk_products_sku_ci
    ON products (LOWER(sku))
    WHERE sku IS NOT NULL;
CREATE INDEX idx_products_category_name ON products (category_id, name);
CREATE INDEX idx_products_operation ON products (active, available, destination);
