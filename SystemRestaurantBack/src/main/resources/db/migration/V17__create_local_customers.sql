-- One restaurant per installation. Profiles are never shared between installations.
CREATE TABLE restaurant_customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(30),
    phone_key VARCHAR(15) UNIQUE,
    email VARCHAR(120),
    preferences VARCHAR(500),
    dietary_notes VARCHAR(300),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_by_username VARCHAR(80) NOT NULL,
    updated_by_username VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_customer_name CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_customer_phone_key CHECK (
        phone_key IS NULL OR phone_key ~ '^[0-9]{7,15}$'
    )
);

CREATE INDEX idx_customers_name ON restaurant_customers (lower(name));

CREATE TABLE restaurant_customer_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES restaurant_customers (id),
    action VARCHAR(20) NOT NULL CHECK (action IN ('CREATED', 'UPDATED', 'ARCHIVED', 'RESTORED')),
    actor_username VARCHAR(80) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_customer_events_history ON restaurant_customer_events (customer_id, occurred_at, id);

ALTER TABLE reservations ADD COLUMN customer_id BIGINT REFERENCES restaurant_customers (id);
CREATE INDEX idx_reservations_customer ON reservations (customer_id, start_at DESC);

ALTER TABLE restaurant_orders ADD COLUMN customer_id BIGINT REFERENCES restaurant_customers (id);
CREATE INDEX idx_orders_customer ON restaurant_orders (customer_id, opened_at DESC);
