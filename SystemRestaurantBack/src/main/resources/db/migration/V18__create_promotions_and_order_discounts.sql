-- Promotions and applied discounts belong to this one local restaurant.
CREATE TABLE promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(24) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    discount_type VARCHAR(12) NOT NULL CHECK (discount_type IN ('PERCENT', 'FIXED')),
    discount_value NUMERIC(12,2) NOT NULL CHECK (discount_value > 0),
    minimum_subtotal NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (minimum_subtotal >= 0),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_by_username VARCHAR(80) NOT NULL,
    updated_by_username VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_promotion_dates CHECK (ends_on >= starts_on),
    CONSTRAINT ck_promotion_percent CHECK (discount_type <> 'PERCENT' OR discount_value <= 90)
);

CREATE TABLE order_discounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL UNIQUE,
    order_id BIGINT NOT NULL REFERENCES restaurant_orders (id),
    promotion_id BIGINT REFERENCES promotions (id),
    source VARCHAR(12) NOT NULL CHECK (source IN ('PROMOTION', 'MANUAL')),
    code_snapshot VARCHAR(24),
    name_snapshot VARCHAR(100) NOT NULL,
    discount_type VARCHAR(12) NOT NULL CHECK (discount_type IN ('PERCENT', 'FIXED')),
    discount_value NUMERIC(12,2) NOT NULL CHECK (discount_value > 0),
    base_subtotal NUMERIC(12,2) NOT NULL CHECK (base_subtotal > 0),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0 AND amount < base_subtotal),
    reason VARCHAR(250),
    status VARCHAR(12) NOT NULL CHECK (status IN ('ACTIVE', 'VOIDED')),
    applied_by_user_id BIGINT NOT NULL REFERENCES app_users (id),
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    voided_by_user_id BIGINT REFERENCES app_users (id),
    voided_at TIMESTAMPTZ,
    void_reason VARCHAR(250),
    CONSTRAINT ck_discount_source CHECK (
        (source = 'PROMOTION' AND promotion_id IS NOT NULL AND code_snapshot IS NOT NULL)
        OR (source = 'MANUAL' AND promotion_id IS NULL AND code_snapshot IS NULL)
    )
);

CREATE UNIQUE INDEX ux_one_active_discount_per_order ON order_discounts (order_id)
    WHERE status = 'ACTIVE';
CREATE INDEX idx_order_discount_history ON order_discounts (order_id, applied_at, id);
